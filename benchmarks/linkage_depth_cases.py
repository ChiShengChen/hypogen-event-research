def snapshot(identifier, issuer, day, horizon, question, sources, *, positive, category, standard):
    documents, anchors = [], {}
    for source_id, url, location, quote, paragraphs in sources:
        documents.append(archived(source_id, day, url, **paragraphs, original=quote))
        anchors[source_id] = {"location": location, "quote": quote}
    return identifier, {
        "issuer": issuer, "split": "pilot" if identifier.startswith("P-") else "holdout",
        "event": Event.model_validate({
            "event_text": question, "research_target": issuer, "research_horizon": horizon,
            "as_of": f"{day}T23:59:59Z", "documents": documents,
        }).model_dump(mode="json"),
        "anchors": anchors,
        "gold": {"positive": positive, "category": category, "standard": standard},
    }


